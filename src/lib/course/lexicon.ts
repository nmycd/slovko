const noun = (gender: "m" | "f" | "n" | null, topic: Topic, plural?: true): WordTags => ({
  pos: "noun",
  ...(gender && { gender }),
  ...(plural && { plural }),
  topic,
});
const say = (topic: Topic, register?: "informal" | "polite"): WordTags => ({
  pos: "expression",
  topic,
  ...(register && { register }),
});

